/* Host-side generator for ../printf-strtod-ref.h, the reference for
   ../tst-printf-strtod.c.  Run it against glibc, whose printf and strtod
   of double are exact:

     gcc -O2 -o gen gen-printf-strtod-ref.c && ./gen > ../printf-strtod-ref.h

   The values are bit patterns, never computed in floating point:
   subnormals, the edges of the normal range, every exponent once with a
   random mantissa, and random doubles.  Each gets glibc's %.17g and %a.
   The second table is strtod input outside what printf produces: values
   that overflow, underflow or need a long exponent.  */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>

static uint64_t rng = 0x9e3779b97f4a7c15ull;
static uint64_t next (void)
{
  rng ^= rng << 13; rng ^= rng >> 7; rng ^= rng << 17;
  return rng;
}

static void emit (uint64_t bits)
{
  double v;
  memcpy (&v, &bits, 8);
  printf ("  { 0x%016llxull, \"%.17g\", \"%a\" },\n", (unsigned long long) bits, v, v);
}

int main (void)
{
  static const double fixed[] = {
    0x1p-1074, 0x1.8p-1073, 0x0.fffffffffffffp-1022, 0x0.8p-1022,
    0x1p-1022, 0x1.0000000000001p-1022, 0x1.fffffffffffffp-1022,
    0x1.fffffffffffffp+1023, 0x1p-1, 0.1, 1.0 / 3, 2.0 / 3,
    0x1.fffffffffffffp-1, 0x1.0000000000001p0, 1e23, 9007199254740993.0,
  };
  static const char *const edge[] = {
    "0x1p1023", "0x1p1024", "0x1.fffffffffffffp1023", "0x1p-1074",
    "0x1p-1075", "0x1p-1076", "0x1p-2000", "0x1p+5000", "0x1p-5000",
    /* the smallest normal with a binary exponent past 1023, where the
       old scaling loop overflowed its factor and returned 0 */
    "0x8p-1025",
    "0x0.00000000000000000000000000000000000001p-1000",
    "0x10000000000000000000000000000000000000p-1100",
    "1e308", "1.7976931348623157e308", "1.7976931348623159e308", "1e309",
    "1e-400", "4.9406564584124654e-324", "2.4703282292062328e-324",
    "2.4703282292062327e-324", "2.2250738585072011e-308",
    "0.000000000000000000000000000000000000000000000000000000000001e-250",
    "100000000000000000000000000000000000000000000000000000000000e250",
  };
  unsigned i;

  printf ("/* Generated by gen/gen-printf-strtod-ref.c on glibc -- do not edit. */\n");
  printf ("static const struct { uint64_t bits; const char *g17, *a; } t[] = {\n");
  for (i = 0; i < sizeof fixed / sizeof *fixed; i++)
    {
      uint64_t b;
      memcpy (&b, &fixed[i], 8);
      emit (b);
      emit (b | 1ull << 63);
    }
  for (i = 0; i < 2047; i++)
    emit ((uint64_t) i << 52 | (next () & 0xfffffffffffffull));
  for (i = 0; i < 2000; i++)
    emit (next () & 0x7fefffffffffffffull);
  printf ("};\n\nstatic const struct { const char *s; uint64_t bits; } edge[] = {\n");
  for (i = 0; i < sizeof edge / sizeof *edge; i++)
    {
      double d = strtod (edge[i], NULL);
      uint64_t b;
      memcpy (&b, &d, 8);
      printf ("  { \"%s\", 0x%016llxull },\n", edge[i], (unsigned long long) b);
    }
  printf ("};\n");
  return 0;
}
